"""Write hashed lock files for the Round 4 research image.

Run inside the image's base (python:3.12-slim) with network access, from this directory:

    python lock.py --cutoff 2026-10-11

For each input file it installs the pins into a fresh venv with wheels only, freezes the
resolved set, and for every pinned version records all published file hashes from PyPI.
It refuses a version uploaded after the cutoff and any version with an OSV advisory, so
transitive packages meet the same age and advisory rules as the direct pins.
"""

import argparse
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

INPUTS = {"requirements.in": "requirements.lock", "requirements-test.in": "requirements-test.lock"}
# Transitive pins held back to meet the cutoff (a newer release exists but is too recent).
CONSTRAINTS = "constraints.txt"


def fetch(url, payload=None):
    data = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def resolve(source):
    with tempfile.TemporaryDirectory() as tmp:
        venv = Path(tmp) / "venv"
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
        pip = str(venv / "bin" / "pip")
        install = [pip, "install", "--quiet", "--disable-pip-version-check", "--only-binary=:all:"]
        subprocess.run([*install, "-c", CONSTRAINTS, "-r", source], check=True)
        frozen = subprocess.run([pip, "freeze", "--all"], check=True, capture_output=True, text=True).stdout
    pins = []
    for line in frozen.splitlines():
        name, _, version = line.partition("==")
        if version and name.lower() not in {"pip", "setuptools", "wheel"}:
            pins.append((name, version))
    return sorted(pins, key=lambda pin: pin[0].lower())


def check(name, version, cutoff):
    release = fetch(f"https://pypi.org/pypi/{name}/{version}/json")
    files = release["urls"]
    uploaded = min(f["upload_time"] for f in files)[:10]
    problems = []
    if uploaded > cutoff:
        problems.append(f"{name}=={version} was uploaded {uploaded}, after the cutoff {cutoff}")
    advisories = fetch(
        "https://api.osv.dev/v1/query", {"version": version, "package": {"name": name, "ecosystem": "PyPI"}}
    ).get("vulns", [])
    if advisories:
        problems.append(f"{name}=={version} has advisories {[a['id'] for a in advisories]}")
    hashes = sorted({f["digests"]["sha256"] for f in files})
    return uploaded, hashes, problems


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cutoff", required=True, help="latest allowed upload date, YYYY-MM-DD")
    args = parser.parse_args()
    problems = []
    outputs = {}
    for source, target in INPUTS.items():
        lines = [f"# Generated by lock.py from {source}, cutoff {args.cutoff}. Do not edit by hand."]
        for name, version in resolve(source):
            uploaded, hashes, found = check(name, version, args.cutoff)
            problems.extend(found)
            lines.append(f"{name}=={version} \\")
            lines.extend(f"    --hash=sha256:{digest} \\" for digest in hashes[:-1])
            lines.append(f"    --hash=sha256:{hashes[-1]}")
            print(f"{target}: {name}=={version} uploaded {uploaded}, {len(hashes)} hashes, {'; '.join(found) or 'ok'}")
        outputs[target] = "\n".join(lines) + "\n"
    if problems:
        raise SystemExit("not locked:\n" + "\n".join(sorted(set(problems))))
    for target, text in outputs.items():
        Path(target).write_text(text)


if __name__ == "__main__":
    main()
